-- Admin-managed product catalog; customers can only read active products.
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
 for all to authenticated
 using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'))
 with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'));
grant insert, update, delete on public.products to authenticated;

drop policy if exists "Admins manage product images" on public.product_images;
create policy "Admins manage product images" on public.product_images
 for all to authenticated
 using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'))
 with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin'));
grant insert, update, delete on public.product_images to authenticated;

-- Order notifications are generated by a private trigger, not by browser-supplied data.
create or replace function private.notify_chinago_order()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
 insert into public.notifications(user_id,title,body,kind)
 values (
  new.customer_id,
  'Demande de commande reçue',
  'Votre demande ' || new.order_number || ' est enregistrée. ChinaGo va vérifier le prix et les frais avant tout paiement.',
  'order'
 );
 return new;
end;
$$;
revoke all on function private.notify_chinago_order() from public, anon, authenticated;
drop trigger if exists notify_chinago_order on public.orders;
create trigger notify_chinago_order after insert on public.orders
 for each row execute function private.notify_chinago_order();

create or replace function public.request_order(
 p_product_id uuid,
 p_store_product_id uuid,
 p_product_title text,
 p_source_url text,
 p_quantity integer,
 p_unit_price_xof numeric,
 p_contact_name text,
 p_contact_phone text,
 p_contact_email text,
 p_delivery_address text,
 p_delivery_city text,
 p_customer_notes text,
 p_cargo_partner_id uuid
) returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
 v_user_id uuid := auth.uid();
 v_order_id uuid := gen_random_uuid();
 v_order_number text := 'CG-' || upper(substr(replace(v_order_id::text, '-', ''), 1, 10));
 v_unit_price numeric(14,2) := 0;
 v_line_total numeric(14,2);
 v_title text := trim(coalesce(p_product_title,''));
begin
 if v_user_id is null then raise exception 'Authentification requise'; end if;
 if p_quantity is null or p_quantity < 1 or p_quantity > 1000 then raise exception 'Quantité invalide'; end if;
 if nullif(v_title, '') is null then raise exception 'Nom du produit requis'; end if;
 if nullif(trim(coalesce(p_contact_name,'')), '') is null or nullif(trim(coalesce(p_contact_phone,'')), '') is null then
   raise exception 'Nom et téléphone requis';
 end if;
 if p_product_id is not null then
   select p.price_xof, p.title into v_unit_price, v_title
   from public.products p where p.id = p_product_id and p.status = 'active';
   if not found then raise exception 'Ce produit n’est plus disponible'; end if;
 elsif p_store_product_id is not null then
   select sp.selling_price_xof, sp.title into v_unit_price, v_title
   from public.store_products sp
   join public.stores s on s.id = sp.store_id
   where sp.id = p_store_product_id and sp.status = 'published' and s.status = 'active';
   if not found then raise exception 'Ce produit de boutique n’est plus disponible'; end if;
 else
   v_unit_price := 0;
 end if;
 if p_cargo_partner_id is not null and not exists (
   select 1 from public.cargo_partners cp where cp.id = p_cargo_partner_id and cp.is_active = true
 ) then raise exception 'Ce transporteur n’est pas disponible'; end if;
 v_unit_price := coalesce(v_unit_price, 0);
 v_line_total := v_unit_price * p_quantity;
 insert into public.orders (
  id, order_number, customer_id, store_id, status, currency,
  subtotal_xof, shipping_xof, total_xof, contact_name, contact_phone,
  contact_email, delivery_address, delivery_city, customer_notes, cargo_partner_id
 ) values (
  v_order_id, v_order_number, v_user_id, null, 'quote_requested', 'XOF',
  v_line_total, 0, v_line_total, trim(p_contact_name), trim(p_contact_phone),
  nullif(trim(coalesce(p_contact_email,'')), ''), trim(coalesce(p_delivery_address,'')),
  trim(coalesce(p_delivery_city,'Lomé')), nullif(trim(coalesce(p_customer_notes,'')), ''),
  p_cargo_partner_id
 );
 insert into public.order_items (
  order_id, product_id, store_product_id, product_title, source_url,
  quantity, unit_price_xof, line_total_xof
 ) values (
  v_order_id, p_product_id, p_store_product_id, v_title, nullif(trim(coalesce(p_source_url,'')), ''),
  p_quantity, v_unit_price, v_line_total
 );
 return v_order_id;
end;
$$;
revoke all on function public.request_order(uuid,uuid,text,text,integer,numeric,text,text,text,text,text,text,uuid) from public, anon;
grant execute on function public.request_order(uuid,uuid,text,text,integer,numeric,text,text,text,text,text,text,uuid) to authenticated;

